/// RDP Set-1 scancode → macOS virtual keycode (T1-IN-02).
///
/// Values are `kVK_*` from HIToolbox `Events.h`. Pure data. Not an `InputSink` method (ISP).
/// Other layouts are incremental later.
public enum UsKeymap {
    public static func virtualKeyCode(scancode: UInt16, isExtended: Bool) -> UInt16? {
        if isExtended {
            return extended[scancode]
        }
        return unextended[scancode]
    }

    public static func virtualKeyCode(for event: InputEvent) -> UInt16? {
        switch event {
        case let .key(scancode, isExtended, _):
            return virtualKeyCode(scancode: scancode, isExtended: isExtended)
        case .mouse:
            return nil
        }
    }

    /// Non-E0 Set-1 scancodes.
    private static let unextended: [UInt16: UInt16] = [
        0x01: 0x35, // Esc
        0x02: 0x12, // 1
        0x03: 0x13, // 2
        0x04: 0x14, // 3
        0x05: 0x15, // 4
        0x06: 0x17, // 5
        0x07: 0x16, // 6
        0x08: 0x1A, // 7
        0x09: 0x1C, // 8
        0x0A: 0x19, // 9
        0x0B: 0x1D, // 0
        0x0C: 0x1B, // Minus
        0x0D: 0x18, // Equal
        0x0E: 0x33, // Delete (Backspace)
        0x0F: 0x30, // Tab
        0x10: 0x0C, // Q
        0x11: 0x0D, // W
        0x12: 0x0E, // E
        0x13: 0x0F, // R
        0x14: 0x11, // T
        0x15: 0x10, // Y
        0x16: 0x20, // U
        0x17: 0x22, // I
        0x18: 0x1F, // O
        0x19: 0x23, // P
        0x1A: 0x21, // LeftBracket
        0x1B: 0x1E, // RightBracket
        0x1C: 0x24, // Return
        0x1D: 0x3B, // Control
        0x1E: 0x00, // A
        0x1F: 0x01, // S
        0x20: 0x02, // D
        0x21: 0x03, // F
        0x22: 0x05, // G
        0x23: 0x04, // H
        0x24: 0x26, // J
        0x25: 0x28, // K
        0x26: 0x25, // L
        0x27: 0x29, // Semicolon
        0x28: 0x27, // Quote
        0x29: 0x32, // Grave
        0x2A: 0x38, // Shift
        0x2B: 0x2A, // Backslash
        0x2C: 0x06, // Z
        0x2D: 0x07, // X
        0x2E: 0x08, // C
        0x2F: 0x09, // V
        0x30: 0x0B, // B
        0x31: 0x2D, // N
        0x32: 0x2E, // M
        0x33: 0x2B, // Comma
        0x34: 0x2F, // Period
        0x35: 0x2C, // Slash
        0x36: 0x3C, // RightShift
        0x37: 0x43, // KeypadMultiply
        0x38: 0x3A, // Option
        0x39: 0x31, // Space
        0x3A: 0x39, // CapsLock
        0x3B: 0x7A, // F1
        0x3C: 0x78, // F2
        0x3D: 0x63, // F3
        0x3E: 0x76, // F4
        0x3F: 0x60, // F5
        0x40: 0x61, // F6
        0x41: 0x62, // F7
        0x42: 0x64, // F8
        0x43: 0x65, // F9
        0x44: 0x6D, // F10
        0x45: 0x47, // NumLock → KeypadClear
        0x47: 0x59, // Keypad7
        0x48: 0x5B, // Keypad8
        0x49: 0x5C, // Keypad9
        0x4A: 0x4E, // KeypadMinus
        0x4B: 0x56, // Keypad4
        0x4C: 0x57, // Keypad5
        0x4D: 0x58, // Keypad6
        0x4E: 0x45, // KeypadPlus
        0x4F: 0x53, // Keypad1
        0x50: 0x54, // Keypad2
        0x51: 0x55, // Keypad3
        0x52: 0x52, // Keypad0
        0x53: 0x41, // KeypadDecimal
        0x57: 0x67, // F11
        0x58: 0x6F, // F12
        0x76: 0x69, // F13 (some layouts)
        0x77: 0x6B, // F14
        0x78: 0x71, // F15
    ]

    /// E0-prefixed Set-1 scancodes.
    private static let extended: [UInt16: UInt16] = [
        0x1C: 0x4C, // KeypadEnter
        0x1D: 0x3E, // RightControl
        0x35: 0x4B, // KeypadDivide
        0x37: 0x69, // PrintScreen → F13
        0x38: 0x3D, // RightOption
        0x47: 0x73, // Home
        0x48: 0x7E, // UpArrow
        0x49: 0x74, // PageUp
        0x4B: 0x7B, // LeftArrow
        0x4D: 0x7C, // RightArrow
        0x4F: 0x77, // End
        0x50: 0x7D, // DownArrow
        0x51: 0x79, // PageDown
        0x52: 0x72, // Insert → Help
        0x53: 0x75, // ForwardDelete
        0x5B: 0x37, // Left GUI → Command
        0x5C: 0x36, // Right GUI → RightCommand
        0x5D: 0x6E, // App → ContextualMenu
    ]
}
